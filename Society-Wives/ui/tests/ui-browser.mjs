import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const screenshots=resolve(dirname(fileURLToPath(import.meta.url)),'../test-screenshots');
mkdirSync(screenshots,{recursive:true});
const base=process.env.SW_BASE_URL || 'http://127.0.0.1:4173/DHIKA_STORY/Society-Wives/';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const errors=[],missing=[];
let pass=0;
const check=(condition,message)=>{assert.ok(condition,message);pass++;console.log('PASS '+message)};
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
page.setDefaultTimeout(25000);
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400 && r.url().startsWith(base))missing.push(r.status()+' '+r.url())});
try {
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.locator('.novel-scene').first().waitFor();
 await page.locator('.novel-scene').last().waitFor();
 check(await page.locator('.novel-scene').count()===17,'Home renders all 17 Episode 01 source scenes');
 check(await page.locator('.main-nav a').count()===5,'Exactly five main destinations');
 check(await page.locator('main a[href^="https://github.com"]').count()===0,'No raw GitHub source links in Home');
 check(await page.getByRole('link',{name:'Return to Home'}).count()===1,'Persistent Home icon present');
 await page.screenshot({path:resolve(screenshots,'01-home-desktop.png')});
 await page.locator('.main-nav a[href="#/reading"]').click();
 await page.locator('.scene-link').first().waitFor();
 check(await page.locator('.scene-link').count()===16,'Ankita Episode 02 reader presents all 16 published archive records');
 check(await page.locator('.perspective-tabs button').count()===6,'Episode 02 offers six perspectives with clean in-app controls');
 check((await page.locator('.source-scene').innerText()).length>150,'Episode scene includes original story prose');
 check(await page.locator('main a[href]').count()===0,'Reader includes no clickable outside source/image links');
 await page.locator('.perspective-tabs button', {hasText:'Shreya'}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.scene-link').length===9);
 check(await page.locator('.scene-link').count()===9,'Shreya Episode 02 opens nine source scenes');
 check(await page.getByRole('button',{name:'Episode 01 · Prologue'}).count()===1,'Clear Episode 01/02 navigation is available within reader');
 await page.locator('.scene-link').last().click();
 await page.waitForFunction(()=>location.hash.includes('SR09'));
 check((await page.locator('.source-scene').innerText()).length>100,'Shreya scene deep link renders original prose');
 await page.reload();
 await page.locator('.source-scene').waitFor();
 check(locationOk(await page.evaluate(()=>location.hash),'SR09'),'Direct scene deep link survives refresh');
 await page.screenshot({path:resolve(screenshots,'02-shreya-reader-desktop.png')});
 await page.locator('.main-nav a[href="#/characters"]').click();
 await page.locator('.cast-name').first().waitFor();
 await page.locator('.perspective-tabs button', {hasText:'Shreya'}).click();
 await page.locator('.cast-name', {hasText:'Poonam'}).click();
 await page.getByRole('heading',{name:'Poonam',exact:true}).first().waitFor();
 check((await page.locator('.profile-panel').innerText()).includes('Sub-Inspector'),'Poonam canonical office role displayed');
 check(await page.locator('main a').count()===0,'Character directory has no scattered external file links');
 await page.screenshot({path:resolve(screenshots,'03-shreya-characters-desktop.png')});
 await page.locator('.main-nav a[href="#/gallery"]').click();
 await page.locator('.image-card').first().waitFor();
 check(await page.locator('.image-card').count()===48,'Gallery contains 48 indexed images (27 GitHub, 21 Drive)');
 await page.locator('label').filter({hasText:'Character'}).locator('select').selectOption('shreya');
 await page.getByText('Poonam — Police Office Portrait 01').waitFor();
 check(await page.getByText('Poonam — Police Office Portrait 01').count()===1,'Shreya storyline filter includes Poonam office portrait');
 await page.getByRole('button',{name:'Inspect Poonam — Police Office Portrait 01'}).click();
 await page.getByRole('dialog').waitFor();
 check((await page.getByRole('dialog').innerText()).includes('not publicly embeddable'),'Private Drive images are not exposed as public thumbnails');
 await page.getByRole('button',{name:'Close image viewer'}).click();
 await page.screenshot({path:resolve(screenshots,'04-shreya-gallery-desktop.png')});
 await page.locator('.main-nav a[href="#/planning"]').click();
 await page.getByRole('heading',{name:'Episode Planning'}).waitFor();
 check((await page.locator('.continuity-cards').innerText()).includes('13:50–14:15'),'Meenakshi Jan 1 13:50–14:15 cut preserved');
 check((await page.locator('.continuity-cards').innerText()).includes('14:15 onwards'),'Episode 04 exact cutpoint preserved');
 check(await page.locator('main a').count()===0,'Planning stays inside the app with no raw source links');
 check(await page.locator('.perspective-tabs button').count()===5,'Planning shows five lead selectors');
 await page.locator('.perspective-tabs button', {hasText:'Shreya'}).click();
 check(await page.locator('.continuity-cards').count()===0,'Shreya planning view does not show unrelated Meenakshi episode cards');
 await page.locator('.perspective-tabs button', {hasText:'Meenakshi'}).click();
 await page.locator('.continuity-cards').waitFor();
 await page.screenshot({path:resolve(screenshots,'05-planning-desktop.png')});
 await page.locator('.home-icon').click();
 await page.locator('.novel-scene').first().waitFor();
 check((await page.locator('.novel-scene').count())===17,'Home icon returns to original prologue');
 // Validate all navigation and story UI at mobile width.
 await page.setViewportSize({width:390,height:844});
 await page.locator('.main-nav a[href="#/gallery"]').click();
 await page.locator('.image-card').first().waitFor();
 const mobile=await page.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
 check(mobile.body<=mobile.viewport+2,'Mobile gallery does not overflow the viewport');
 const navBoxes=await page.locator('.main-nav a').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {left:r.left,right:r.right,width:r.width}}));
 check(navBoxes.length===5&&navBoxes.every(r=>r.width>20&&r.left>=-1&&r.right<=391),'All five mobile navigation links are visible without scrolling');
 await page.screenshot({path:resolve(screenshots,'06-gallery-mobile.png')});
 await page.locator('.main-nav a[href="#/reading"]').click();
 await page.locator('.source-scene').waitFor();
 const mobileReader=await page.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
 check(mobileReader.body<=mobileReader.viewport+2,'Mobile reader does not overflow viewport');
 const sceneScroller=await page.locator('.scene-sidebar').evaluate(el=>({scrollWidth:el.scrollWidth,clientWidth:el.clientWidth}));
 check(sceneScroller.scrollWidth>sceneScroller.clientWidth,'Mobile reader scene chips can be swiped horizontally without label collisions');
 await page.screenshot({path:resolve(screenshots,'07-reader-mobile.png')});
 check(errors.length===0,'No uncaught browser JavaScript exceptions');
 check(missing.length===0,'No failed same-site static asset or source requests: '+missing.slice(0,4).join(', '));
 console.log('VISUAL UI TEST COMPLETE: '+pass+' assertions passed. Screenshots: '+screenshots);
} catch(err){
 console.error('UI TEST FAILED:',err.message);
 console.error('Browser errors:',errors);
 console.error('Missing responses:',missing.slice(0,20));
 await page.screenshot({path:resolve(screenshots,'ERROR-last-screen.png')}).catch(()=>{});
 process.exitCode=1;
} finally {await browser.close()}
function locationOk(hash,expected){return hash.includes(expected)}
